function buildItems(sites, category, startingIndex) {
  const baseBannerUrl = categoryBannerUrls[category] ?? 'https://images.unsplash.com/photo-1529400971008-f566de0e6dfc?auto=format&fit=crop&w=800&q=80';

  return sites.map((site, index) => ({
    id: `tbcpl-${String(startingIndex + index).padStart(3, '0')}`,
    title: site.title,
    category,
    type: typeByCategory[category] || 'platform',
    url: site.url,
    embedUrl: '',
    description: `Browse free and curated streaming content on ${site.title}.`,
    rating: 4.4,
    year: '2026',
    views: '0',
    featured: false,
    isTrending: false,
    bannerUrl: LOGO_MAP[site.title] || `${baseBannerUrl}&sig=${startingIndex + index}`
  }));
}

